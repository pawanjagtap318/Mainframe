CREATE SEQUENCE AETHR.ACCT_SEQ
  AS BIGINT
  START WITH 1420008003
  INCREMENT BY 1
  NO CYCLE;

CREATE SEQUENCE AETHR.TXN_SEQ
  AS BIGINT
  START WITH 1
  INCREMENT BY 1
  NO CYCLE;

CREATE TABLE AETHR.CUSTOMER (
  CUST_ID      CHAR(8)       NOT NULL,
  FULL_NAME    VARCHAR(60)   NOT NULL,
  PAN_NO       CHAR(10)      NOT NULL,
  CITY         VARCHAR(30)   NOT NULL,
  PHONE        CHAR(10)      NOT NULL,
  KYC_STATUS   CHAR(1)       NOT NULL,
  OPEN_DATE    DATE          NOT NULL,
  EMAIL        VARCHAR(40)   NOT NULL,
  CONSTRAINT PK_CUSTOMER PRIMARY KEY (CUST_ID),
  CONSTRAINT CK_CUSTOMER_KYC CHECK (KYC_STATUS IN ('V', 'P'))
);

CREATE TABLE AETHR.ACCOUNT (
  ACCT_NO       CHAR(10)       NOT NULL,
  CUST_ID       CHAR(8)        NOT NULL,
  ACCT_TYPE     CHAR(3)        NOT NULL,
  BALANCE       DECIMAL(15,2)  NOT NULL,
  RATE          DECIMAL(5,2)   NOT NULL,
  STATUS        CHAR(1)        NOT NULL,
  BRANCH_CODE   CHAR(4)        NOT NULL,
  OPEN_DATE     DATE           NOT NULL,
  LAST_INT_DATE DATE           NOT NULL,
  MATURITY_DATE DATE,
  CONSTRAINT PK_ACCOUNT PRIMARY KEY (ACCT_NO),
  CONSTRAINT FK_ACCOUNT_CUSTOMER FOREIGN KEY (CUST_ID)
    REFERENCES AETHR.CUSTOMER (CUST_ID),
  CONSTRAINT CK_ACCOUNT_TYPE CHECK (ACCT_TYPE IN ('SAV', 'CUR', 'FD')),
  CONSTRAINT CK_ACCOUNT_STATUS CHECK (STATUS IN ('A', 'F', 'C')),
  CONSTRAINT CK_ACCOUNT_BALANCE CHECK (BALANCE >= 0)
);

CREATE INDEX AETHR.IX_ACCOUNT_CUSTOMER
  ON AETHR.ACCOUNT (CUST_ID, ACCT_NO);

CREATE TABLE AETHR.TXN (
  TXN_ID        CHAR(12)       NOT NULL,
  ACCT_NO       CHAR(10)       NOT NULL,
  TXN_TS        TIMESTAMP      NOT NULL,
  DR_CR         CHAR(1)        NOT NULL,
  AMOUNT        DECIMAL(15,2)  NOT NULL,
  BAL_AFTER     DECIMAL(15,2)  NOT NULL,
  NARRATIVE     VARCHAR(60)    NOT NULL,
  CHANNEL       CHAR(4)        NOT NULL,
  RELATED_ACCT  CHAR(10),
  PROGRAM_ID    CHAR(8)        NOT NULL,
  TELLER_ID     CHAR(8)        NOT NULL,
  CONSTRAINT PK_TXN PRIMARY KEY (TXN_ID),
  CONSTRAINT FK_TXN_ACCOUNT FOREIGN KEY (ACCT_NO)
    REFERENCES AETHR.ACCOUNT (ACCT_NO),
  CONSTRAINT CK_TXN_DRCR CHECK (DR_CR IN ('D', 'C')),
  CONSTRAINT CK_TXN_AMOUNT CHECK (AMOUNT > 0)
);

CREATE INDEX AETHR.IX_TXN_ACCOUNT_TIME
  ON AETHR.TXN (ACCT_NO, TXN_TS);

CREATE TABLE AETHR.BATCH_RUN (
  RUN_ID       INTEGER        NOT NULL,
  JOB_NAME     CHAR(8)        NOT NULL,
  JOB_ID       CHAR(8)        NOT NULL,
  STATUS       CHAR(10)       NOT NULL,
  RETURN_CODE  SMALLINT       NOT NULL,
  SUBMITTED_AT TIMESTAMP      NOT NULL,
  ENDED_AT     TIMESTAMP      NOT NULL,
  PROGRAM_ID   CHAR(8)        NOT NULL,
  SPOOL        CLOB(64K),
  CONSTRAINT PK_BATCH_RUN PRIMARY KEY (RUN_ID)
);
